import { SignJWT, jwtVerify, importPKCS8, importSPKI, exportJWK } from "jose";

const ALG = "RS256";
const KEY_ID = process.env.OAUTH_KEY_ID || "o-auth-key-1";

// Must match /.well-known/openid-configuration "issuer"
const ISSUER =
  process.env.OAUTH_ISSUER ||
  (process.env.NEXTAUTH_URL || "http://localhost:3000").replace(/\/$/, "");

let cachedPrivateKey = null;
let cachedPublicKey = null;

function pem(value) {
  // .env stores PEM with literal \n escapes; restore real newlines.
  return value.replace(/\\n/g, "\n");
}

async function getPrivateKey() {
  if (!cachedPrivateKey) {
    if (!process.env.OAUTH_PRIVATE_KEY) {
      throw new Error(
        "OAUTH_PRIVATE_KEY is not set. Run `npm run keys:generate` and copy the output into .env."
      );
    }
    cachedPrivateKey = await importPKCS8(pem(process.env.OAUTH_PRIVATE_KEY), ALG);
  }
  return cachedPrivateKey;
}

async function getPublicKey() {
  if (!cachedPublicKey) {
    if (!process.env.OAUTH_PUBLIC_KEY) {
      throw new Error(
        "OAUTH_PUBLIC_KEY is not set. Run `npm run keys:generate` and copy the output into .env."
      );
    }
    cachedPublicKey = await importSPKI(pem(process.env.OAUTH_PUBLIC_KEY), ALG);
  }
  return cachedPublicKey;
}

/**
 * Sign a short-lived access token JWT.
 * `jti` is generated by the caller and persisted in the AccessToken table
 * so revocation/introspection can look it up without decoding the JWT.
 */
export async function signAccessToken({ jti, sub, clientId, scopes, ttlSeconds }) {
  const key = await getPrivateKey();
  const now = Math.floor(Date.now() / 1000);

  return new SignJWT({
    scope: scopes.join(" "),
    client_id: clientId,
  })
    .setProtectedHeader({ alg: ALG, kid: KEY_ID, typ: "JWT" })
    .setSubject(sub)
    .setJti(jti)
    .setIssuedAt(now)
    .setExpirationTime(now + ttlSeconds)
    .setIssuer(ISSUER)
    .sign(key);
}

/** Verify an access token's signature and expiry. Throws on failure. */
export async function verifyAccessToken(token) {
  const key = await getPublicKey();
  const { payload } = await jwtVerify(token, key, { issuer: ISSUER });
  return payload;
}

/**
 * Sign an OpenID Connect ID Token (JWT).
 * Only issued when the "openid" scope is present.
 */
export async function signIdToken({
  sub,
  clientId,
  ttlSeconds = 3600,
  email = null,
  name = null,
  authTime = null,
  nonce = null,
}) {
  const key = await getPrivateKey();
  const now = Math.floor(Date.now() / 1000);

  const payload = {};

  // Optional standard claims
  if (email) payload.email = email;
  if (name) payload.name = name;
  if (authTime) payload.auth_time = authTime;
  if (nonce) payload.nonce = nonce;

  return new SignJWT(payload)
    .setProtectedHeader({ alg: ALG, kid: KEY_ID, typ: "JWT" })
    .setSubject(sub)
    .setAudience(clientId) // ID Token audience is always the client_id
    .setIssuer(ISSUER)
    .setIssuedAt(now)
    .setExpirationTime(now + ttlSeconds)
    .sign(key);
}

/** Public JWKS document, served at /api/oauth/keys for token verification by clients. */
export async function getJwks() {
  const key = await getPublicKey();
  const jwk = await exportJWK(key);
  return {
    keys: [
      {
        ...jwk,
        kid: KEY_ID,
        use: "sig",
        alg: ALG,
      },
    ],
  };
}